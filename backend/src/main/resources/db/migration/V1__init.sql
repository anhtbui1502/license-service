-- Schema MVP cho License Manager.
-- Viết theo cú pháp chung để chạy được trên PostgreSQL (prod) và H2 MODE=PostgreSQL (test).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    full_name     VARCHAR(200),
    email         VARCHAR(200) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    password_hash VARCHAR(200) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN', 'OPERATOR', 'VIEWER'))
);

CREATE TABLE market (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(20)  NOT NULL UNIQUE,
    name             VARCHAR(200) NOT NULL,
    country          VARCHAR(100),
    license_required BOOLEAN      NOT NULL DEFAULT TRUE,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    note             VARCHAR(1000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE
);

CREATE TABLE license_request (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_code      VARCHAR(40)  NOT NULL UNIQUE,
    market_id         BIGINT       NOT NULL REFERENCES market (id),
    prev_license_id   BIGINT,
    max_sub           BIGINT       NOT NULL,
    max_active_sub    BIGINT       NOT NULL,
    reason            VARCHAR(2000) NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    -- Bằng market_id khi status = PENDING_OTP, NULL ở mọi trạng thái khác.
    -- UNIQUE => mỗi thị trường tối đa 1 yêu cầu đang chờ OTP (DB tự chặn race condition).
    pending_market_id BIGINT UNIQUE,
    requested_by      BIGINT       NOT NULL REFERENCES app_user (id),
    approver_email    VARCHAR(200) NOT NULL,
    otp_hash          VARCHAR(128),
    otp_expires_at    TIMESTAMP WITH TIME ZONE,
    otp_last_sent_at  TIMESTAMP WITH TIME ZONE,
    otp_resend_count  INT          NOT NULL DEFAULT 0,
    otp_attempt_count INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    closed_at         TIMESTAMP WITH TIME ZONE,
    closed_by         VARCHAR(100),
    CONSTRAINT ck_req_numbers CHECK (max_sub > 0 AND max_active_sub > 0 AND max_active_sub <= max_sub),
    CONSTRAINT ck_req_status CHECK (status IN ('PENDING_OTP', 'GENERATED', 'EXPIRED', 'CANCELLED', 'FAILED')),
    CONSTRAINT ck_req_pending CHECK (
        (status = 'PENDING_OTP' AND pending_market_id = market_id)
        OR (status <> 'PENDING_OTP' AND pending_market_id IS NULL))
);

CREATE INDEX ix_req_market ON license_request (market_id, created_at);
CREATE INDEX ix_req_status ON license_request (status, otp_expires_at);

CREATE TABLE license_file (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_code   VARCHAR(60)  NOT NULL UNIQUE,
    market_id      BIGINT       NOT NULL REFERENCES market (id),
    request_id     BIGINT UNIQUE REFERENCES license_request (id),
    version        INT          NOT NULL,
    max_sub        BIGINT       NOT NULL,
    max_active_sub BIGINT       NOT NULL,
    file_name      VARCHAR(255) NOT NULL,
    file_content   BYTEA        NOT NULL,
    file_sha256    VARCHAR(64)  NOT NULL,
    crypto_name    VARCHAR(50)  NOT NULL,
    is_current     BOOLEAN      NOT NULL DEFAULT FALSE,
    issued_by      BIGINT REFERENCES app_user (id),
    issued_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_license_version UNIQUE (market_id, version)
);

ALTER TABLE license_request
    ADD CONSTRAINT fk_req_prev_license FOREIGN KEY (prev_license_id) REFERENCES license_file (id);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(100),
    action      VARCHAR(50)  NOT NULL,
    entity_type VARCHAR(50),
    entity_id   BIGINT,
    detail      VARCHAR(4000),
    ip_address  VARCHAR(64),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_audit_action_time ON audit_log (action, created_at);
CREATE INDEX ix_audit_time ON audit_log (created_at);
